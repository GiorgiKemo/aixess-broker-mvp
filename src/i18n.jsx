const LanguageContext = createContext(null);
const STORAGE_KEY = "aixess-language";

export function localizeFieldValidation(event, t) {
  const field = event.target;
  field.setCustomValidity("");
  field.setCustomValidity(t(field.validity.valueMissing ? "requiredField" : field.type === "email" && field.validity.typeMismatch ? "invalidEmail" : "invalidField"));
}

export function clearFieldValidation(event) {
  event.target.setCustomValidity?.("");
}

function initialLocale() {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (LANGUAGE_OPTIONS.some((language) => language.code === saved)) return saved;
  const browserLanguage = window.navigator.language?.slice(0, 2).toLowerCase();
  return LANGUAGE_OPTIONS.some((language) => language.code === browserLanguage) ? browserLanguage : "en";
}

export function LanguageProvider({ children }) {
  const [locale, setLocaleState] = useState(initialLocale);

  const setLocale = useCallback((nextLocale) => {
    if (!LANGUAGE_OPTIONS.some((language) => language.code === nextLocale)) return;
    setLocaleState(nextLocale);
    window.localStorage.setItem(STORAGE_KEY, nextLocale);
  }, []);

  useLayoutEffect(() => {
    document.documentElement.lang = locale;
    document.title = TRANSLATIONS[locale].siteTitle;
    document.querySelector('meta[name="description"]')?.setAttribute("content", TRANSLATIONS[locale].aSharperRoute);
  }, [locale]);

  const t = useCallback((key, variables = {}) => {
    const value = TRANSLATIONS[locale]?.[key] ?? ENGLISH[key] ?? key;
    return String(value).replace(/\{\{(\w+)\}\}/g, (_, variable) => String(variables[variable] ?? ""));
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t, languages: LANGUAGE_OPTIONS }), [locale, setLocale, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (context) return context;
  const t = (key, variables = {}) => String(ENGLISH[key] ?? key).replace(/\{\{(\w+)\}\}/g, (_, variable) => String(variables[variable] ?? ""));
  return { locale: "en", setLocale: () => {}, t, languages: LANGUAGE_OPTIONS };
}
